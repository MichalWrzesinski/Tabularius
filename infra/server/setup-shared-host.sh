#!/usr/bin/env bash
# Prepares the owner's SHARED server (other projects, the host's nginx with certbot on 80/443, Docker installed) for
# Tabularius staging. Changes nothing server-wide: no firewall, SSH settings or packages. Idempotent. Run as root:
#
#   sudo bash setup-shared-host.sh <domain> "<deploy SSH public key>" \
#       [app_dir=/srv/Tabularius] [deploy_user=tabularius_deploy] [proxy_port=8091] [subnet=172.29.0.0/24]
#
# Creates the deploy user (SSH key only, `restrict`ed, member of the docker group), the app directory and its .env
# with generated database passwords and secrets (they never leave the server).
set -euo pipefail

DOMAIN="${1:?domain required}"
DEPLOY_PUBKEY="${2:?deploy SSH public key required}"
APP_DIR="${3:-/srv/Tabularius}"
DEPLOY_USER="${4:-tabularius_deploy}"
PROXY_PORT="${5:-8091}"
SUBNET="${6:-172.29.0.0/24}"

fail() { echo "ERROR: $*" >&2; exit 1; }
[[ "$(id -u)" == 0 ]] || fail "run as root (sudo)"
[[ "$DOMAIN" =~ ^[a-z0-9.-]+$ ]] || fail "invalid domain"
[[ "$APP_DIR" =~ ^/srv/[A-Za-z0-9._-]+$ ]] || fail "app_dir must be a directory directly in /srv"
[[ "$DEPLOY_USER" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]] || fail "invalid user name"
[[ "$PROXY_PORT" =~ ^[0-9]{4,5}$ ]] || fail "invalid port"
[[ "$SUBNET" =~ ^([0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3})\.0/24$ ]] || fail "subnet must be a /24, e.g. 172.29.0.0/24"
GATEWAY="${BASH_REMATCH[1]}.1"   # the host's nginx reaches the edge proxy through this address

command -v docker >/dev/null || fail "Docker is not installed"
docker compose version >/dev/null || fail "the Docker Compose plugin is not installed"
getent group docker >/dev/null || fail "the docker group does not exist"
command -v openssl >/dev/null || fail "openssl is not installed"

key_file="$(mktemp)"
printf '%s\n' "$DEPLOY_PUBKEY" > "$key_file"
ssh-keygen -lf "$key_file" >/dev/null || { rm -f "$key_file"; fail "the deploy key is not a valid SSH public key"; }
rm -f "$key_file"

echo "==> Checks on the shared host"
NET16="$(cut -d. -f1-2 <<<"${GATEWAY%.1}")."
while read -r net; do
  [[ "$net" == tabularius_internal ]] && continue
  if docker network inspect "$net" --format '{{range .IPAM.Config}}{{.Subnet}} {{end}}' | grep -q "^$NET16\| $NET16"; then
    fail "Docker network '$net' uses addresses in ${NET16}0.0/16; pass another subnet as the 6th argument"
  fi
done < <(docker network ls --format '{{.Name}}')
if ip -4 route | grep -v "br-" | grep -q "^$NET16"; then
  fail "a host route already uses ${NET16}0.0/16; pass another subnet as the 6th argument"
fi
if ss -Htln "sport = :$PROXY_PORT" | grep -q .; then
  docker ps --format '{{.Names}} {{.Ports}}' | grep -q "^tabularius-edge.*127.0.0.1:$PROXY_PORT->" \
    || fail "port $PROXY_PORT is already used on this server; pass another port as the 5th argument"
fi

echo "==> Deploy user $DEPLOY_USER (SSH key only)"
MARKER=.tabularius-deploy-user
if id "$DEPLOY_USER" >/dev/null 2>&1; then
  home="$(getent passwd "$DEPLOY_USER" | cut -d: -f6)"
  [[ -f "$home/$MARKER" ]] || fail "user $DEPLOY_USER already exists and was not created by this script; choose another name"
else
  useradd --create-home --shell /bin/bash "$DEPLOY_USER"
  passwd -l "$DEPLOY_USER" >/dev/null
  home="$(getent passwd "$DEPLOY_USER" | cut -d: -f6)"
  touch "$home/$MARKER"
fi
usermod -aG docker "$DEPLOY_USER"
install -d -m 700 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$home/.ssh"
touch "$home/.ssh/authorized_keys"
# `restrict`: commands and scp only — no port forwarding, agent forwarding or terminal.
key_line="restrict $DEPLOY_PUBKEY"
grep -qxF "$key_line" "$home/.ssh/authorized_keys" || printf '%s\n' "$key_line" >> "$home/.ssh/authorized_keys"
chown "$DEPLOY_USER:$DEPLOY_USER" "$home/.ssh/authorized_keys"
chmod 600 "$home/.ssh/authorized_keys"

echo "==> $APP_DIR"
# A directory with other files (the temporary page nginx serves now) is never taken over or deleted.
if [[ -d "$APP_DIR" && ! -f "$APP_DIR/.env" ]] && [[ -n "$(ls -A "$APP_DIR")" ]]; then
  fail "$APP_DIR already contains files; move them elsewhere first (docs/runbook.md, Staging)"
fi
install -d -m 750 -o "$DEPLOY_USER" -g "$DEPLOY_USER" "$APP_DIR" "$APP_DIR/releases"

if [[ -f "$APP_DIR/.env" ]]; then
  echo "    .env exists — left unchanged"
else
  secret() { openssl rand -hex "$1"; }
  cat > "$APP_DIR/.env" <<ENV
# Generated by setup-shared-host.sh on $(date -u +%Y-%m-%d). Server-only; never commit or copy.
DOMAIN=$DOMAIN
PROXY_PORT=$PROXY_PORT
INTERNAL_SUBNET=$SUBNET
TRUSTED_PROXIES=$GATEWAY/32
POSTGRES_PASSWORD=$(secret 24)
TABULARIUS_MIGRATOR_PASSWORD=$(secret 24)
TABULARIUS_APP_PASSWORD=$(secret 24)
BUSINESS_OWNER_PASSWORD=$(secret 24)
BUSINESS_READER_PASSWORD=$(secret 24)
API_APP_SECRET=$(secret 32)
BUSINESS_APP_SECRET=$(secret 32)
BUSINESS_API_TOKEN=$(secret 32)
# Public demo credential shown on the login screens (shared demo accounts, brief §4.1).
DEMO_SHARED_PASSWORD=Demo123!
MAILER_FROM=tabularius@gitpush.app
ENV
  chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR/.env"
  chmod 600 "$APP_DIR/.env"
fi

cat <<NOTE
==> Done.
Next (docs/runbook.md, "Staging"):
  1. nginx: install infra/server/nginx-tabularius.conf as the site for $DOMAIN (port $PROXY_PORT).
  2. Check the key login: ssh $DEPLOY_USER@<server> 'docker ps' (from the machine with the key).
  3. GitHub secrets, then the first deployment.
Note: the docker group is root-equivalent on this whole server, including the other projects.
Keep the deploy key only in the GitHub secret (it is limited with "restrict").
NOTE
